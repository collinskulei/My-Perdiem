-- Step 1: Safety checks - every group must still match the audit exactly.
do $$
declare bad text;
begin
  select string_agg(format('%s: %s rows / KES %s (expected %s / %s)', e.grp, coalesce(a.n, 0), coalesce(a.s, 0), e.n, e.s), '; ')
  into bad
  from (values
    ('jul_to_apr', 44, 8421800),
    ('oct_to_apr', 35, 797600),
    ('oct_to_jul', 850, 8758300),
    ('dec_to_jul', 202, 9744700),
    ('jun26_to_jun25', 111, 1388100)
  ) as e(grp, n, s)
  left join (
    select f.grp, count(*) as n, sum(p.total_perdiem) as s
    from date_fixes f join perdiem_requests p on p.id = f.id and p.date = f.old_date
    where coalesce(p.recovered_amount, 0) = 0
    group by f.grp
  ) a on a.grp = e.grp
  where coalesce(a.n, 0) <> e.n or coalesce(a.s, 0) <> e.s;
  if bad is not null then raise exception 'Date-fix safety check failed: %', bad; end if;

  select string_agg(format('%s: %s pairs / KES %s (expected %s / %s)', e.grp, coalesce(a.n, 0), coalesce(a.s, 0), e.n, e.s), '; ')
  into bad
  from (values
    ('sep_dups', 17, 1020200),
    ('dec_dups', 21, 537600)
  ) as e(grp, n, s)
  left join (
    select d.grp, count(*) as n, sum(r.total_perdiem) as s
    from dup_pairs d
    join perdiem_requests r on r.id = d.remove_id
    join perdiem_requests k on k.id = d.keep_id
    where r.participant_phone = k.participant_phone
      and r.total_perdiem = k.total_perdiem
      and coalesce(r.transport_allowance, 0) = coalesce(k.transport_allowance, 0)
      and coalesce(r.dsa_allowance, 0) = coalesce(k.dsa_allowance, 0)
      and coalesce(r.recovered_amount, 0) = 0 and not coalesce(r.is_overpayment, false)
    group by d.grp
  ) a on a.grp = e.grp
  where coalesce(a.n, 0) <> e.n or coalesce(a.s, 0) <> e.s;
  if bad is not null then raise exception 'Duplicate safety check failed: %', bad; end if;

  if exists (select 1 from dup_pairs d join date_fixes f on f.id in (d.remove_id, d.keep_id)) then
    raise exception 'A row is in both the date fixes and the duplicate pairs';
  end if;
end $$;

-- Step 2: Backups. Undo the date fixes with:
--   update perdiem_requests p set date = b.old_date
--   from perdiem_requests_backup_2025_date_fixes_b2 b where p.id = b.id;
-- Undo the deletes with:
--   insert into perdiem_requests select * from perdiem_requests_backup_2025_duplicates_b2;
create table perdiem_requests_backup_2025_date_fixes_b2 as
  select f.id, f.old_date, f.new_date, f.grp, p.event_id, now() as changed_at
  from date_fixes f join perdiem_requests p on p.id = f.id;
create table perdiem_requests_backup_2025_duplicates_b2 as
  select p.* from perdiem_requests p where p.id in (select remove_id from dup_pairs);

-- Step 3: Move the dates.
do $$
declare n int;
begin
  update perdiem_requests p set date = f.new_date
  from date_fixes f where p.id = f.id and p.date = f.old_date;
  get diagnostics n = row_count;
  if n <> 1242 then raise exception 'Expected to update 1242 rows, updated %', n; end if;
end $$;

-- Step 4: Delete the duplicate copies.
do $$
declare n int;
begin
  delete from perdiem_requests where id in (select remove_id from dup_pairs);
  get diagnostics n = row_count;
  if n <> 38 then raise exception 'Expected to delete 38 rows, deleted %', n; end if;
end $$;

-- Step 5: Keep each touched event's date list in line - add the new dates,
-- then drop any old date that no payment on that event uses any more.
update events e
set event_dates = e.event_dates || array(select x from unnest(s.new_dates) x where not (x = any(e.event_dates)))
from (select event_id, array_agg(distinct new_date) as new_dates
      from perdiem_requests_backup_2025_date_fixes_b2 group by event_id) s
where e.id = s.event_id;

update events e
set event_dates = array(
  select x from unnest(e.event_dates) x
  where not (x = any(s.old_dates))
     or exists (select 1 from perdiem_requests p where p.event_id = e.id and p.date = x))
from (select event_id, array_agg(distinct d) as old_dates
      from (select event_id, old_date as d from perdiem_requests_backup_2025_date_fixes_b2
            union all
            select event_id, date from perdiem_requests_backup_2025_duplicates_b2) o
      group by event_id) s
where e.id = s.event_id;

commit;

